/**
 * Generates `src/i18n/catalog/en/meta.ts` from the analysis registry, so the
 * English labels/descriptions stay single-sourced.
 *
 * Run: `node --import tsx scripts/i18n-meta.mjs`
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ANALYSIS_FAMILIES, ANALYSIS_TABS } from '../src/analyses/registry.ts';

const q = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const lines = [];
for (const family of ANALYSIS_FAMILIES) {
  lines.push(`  ${q(`meta.family.${family.id}.label`)}: ${q(family.label)},`);
  lines.push(`  ${q(`meta.family.${family.id}.description`)}: ${q(family.description)},`);
}
for (const analysis of ANALYSIS_TABS) {
  lines.push(`  ${q(`meta.analysis.${analysis.id}.label`)}: ${q(analysis.label)},`);
  lines.push(`  ${q(`meta.analysis.${analysis.id}.description`)}: ${q(analysis.description)},`);
}

const text = `/** English messages — registry metadata (generated by scripts/i18n-meta.mjs). */
export const metaMessages = {
${lines.join('\n')}
} as const;
`;
writeFileSync(join(process.cwd(), 'src/i18n/catalog/en/meta.ts'), text);
console.log(`meta: ${lines.length} keys`);
