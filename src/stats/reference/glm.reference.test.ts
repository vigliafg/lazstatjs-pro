import test from 'node:test';
import assert from 'node:assert/strict';
import { addIntercept, glmFit, type GlmFamily, type GlmLink } from '../kernels/glm';
import { assertClose, assertCloseVector, loadFixture, TOLERANCES } from './harness';

interface GlmFixtureCase {
  name: string;
  family: GlmFamily;
  link: GlmLink;
  y: number[];
  x: number[][];
  coefficients: { beta: number; se: number }[];
  deviance: number;
  nullDeviance: number;
  logLik: number;
  aic: number;
  dispersion: number;
}

interface GlmFixture {
  source: string;
  generatedBy: string;
  cases: GlmFixtureCase[];
}

const fixture = loadFixture<GlmFixture>('glm.json');

// Demonstrative reference test (W0-04): the fixture is generated by
// `src/stats/reference/r/glm.R` from R's glm() and committed, so this test
// exercises the full harness without requiring R at test time.
test('GLM matches the R glm fixtures generated by the reference harness', () => {
  assert.ok(fixture.cases.length >= 5);
  for (const reference of fixture.cases) {
    const fit = glmFit({
      y: reference.y,
      x: addIntercept(reference.x),
      family: reference.family,
      link: reference.link,
    });
    assert.ok(fit, `${reference.name}: model did not converge`);

    assertCloseVector(
      fit!.coefficients.map(coefficient => coefficient.beta),
      reference.coefficients.map(coefficient => coefficient.beta),
      TOLERANCES.rProbability,
      `${reference.name} beta`
    );
    assertCloseVector(
      fit!.coefficients.map(coefficient => coefficient.se),
      reference.coefficients.map(coefficient => coefficient.se),
      TOLERANCES.rProbability,
      `${reference.name} se`
    );

    assertClose(fit!.deviance, reference.deviance, TOLERANCES.rProbability, `${reference.name} deviance`);
    assertClose(
      fit!.nullDeviance,
      reference.nullDeviance,
      TOLERANCES.rProbability,
      `${reference.name} null deviance`
    );
    assertClose(fit!.logLik, reference.logLik, TOLERANCES.rProbability, `${reference.name} logLik`);
    assertClose(fit!.aic, reference.aic, TOLERANCES.rProbability, `${reference.name} AIC`);
    assertClose(
      fit!.dispersion,
      reference.dispersion,
      TOLERANCES.rProbability,
      `${reference.name} dispersion`
    );
  }
});

test('the harness rejects values outside the declared tolerance', () => {
  assert.throws(() => assertClose(1.001, 1, TOLERANCES.r));
  assert.throws(() => assertCloseVector([1, 2], [1, 3], TOLERANCES.r));
  assertClose(1.0000001, 1, TOLERANCES.rProbability);
  assertClose(1000.0000001, 1000, { absolute: 0, relative: 1e-9 });
});
