import test from 'node:test';
import assert from 'node:assert/strict';
import { fitIv } from '../kernels/iv';
import { assertClose, assertCloseVector, loadFixture } from './harness';

interface IvFixtureCoefficient {
  term: string;
  beta: number;
  se: number;
}

interface IvFixtureFirstStage {
  endog: string;
  terms: string[];
  coefficients: IvFixtureCoefficient[];
  f: number;
  df1: number;
  df2: number;
  p: number;
}

interface IvFixtureCase {
  name: string;
  robust: boolean;
  terms: string[];
  coefficients: IvFixtureCoefficient[];
  fitted: number[];
  residuals: number[];
  r2: number;
  adjR2: number;
  sigma: number;
  firstStage: IvFixtureFirstStage[];
  sargan: { statistic: number; df: number; p: number };
  wuHausman: { statistic: number; df1: number; df2: number; p: number };
}

interface IvFixture {
  source: string;
  generatedBy: string;
  dataset: string;
  formula: string;
  data: {
    y: number[];
    /** Columns of the endogenous regressors. */
    endog: number[][];
    /** Columns of the excluded instruments. */
    instruments: number[][];
    /** Columns of the included exogenous regressors. */
    exog: number[][];
  };
  cases: IvFixtureCase[];
}

const fixture = loadFixture<IvFixture>('iv.json');

/** Transpose column-major fixture data into one row per observation. */
const rowsOf = (columns: number[][]): number[][] =>
  (columns[0] ?? []).map((_, row) => columns.map(column => column[row]));

const TOLERANCE = 1e-6;

test('IV/2SLS matches the AER::ivreg fixtures generated by the reference harness', () => {
  assert.ok(fixture.cases.length >= 2);
  const y = fixture.data.y;
  const endog = rowsOf(fixture.data.endog);
  const instruments = rowsOf(fixture.data.instruments);
  const exog = rowsOf(fixture.data.exog);

  for (const reference of fixture.cases) {
    const fit = fitIv({
      y,
      endog,
      instruments,
      exog,
      robust: reference.robust,
      level: 95,
    });
    assert.ok(fit, `${reference.name}: model was not estimated`);

    assert.equal(fit!.n, y.length, `${reference.name}: n`);
    assert.equal(fit!.p, reference.coefficients.length, `${reference.name}: p`);
    assert.equal(fit!.dfResidual, y.length - reference.coefficients.length, `${reference.name}: df`);

    // Structural equation.
    assertCloseVector(
      fit!.coefficients.map(value => value.beta),
      reference.coefficients.map(value => value.beta),
      TOLERANCE,
      `${reference.name} beta`
    );
    assertCloseVector(
      fit!.coefficients.map(value => value.se),
      reference.coefficients.map(value => value.se),
      TOLERANCE,
      `${reference.name} se`
    );
    assertCloseVector(fit!.fitted, reference.fitted, TOLERANCE, `${reference.name} fitted`);
    assertCloseVector(fit!.residuals, reference.residuals, TOLERANCE, `${reference.name} residuals`);
    assertClose(fit!.r2, reference.r2, TOLERANCE, `${reference.name} R²`);
    assertClose(fit!.adjR2, reference.adjR2, TOLERANCE, `${reference.name} adjusted R²`);
    assertClose(fit!.sigma, reference.sigma, TOLERANCE, `${reference.name} sigma`);

    // First stage: coefficients, partial F of the excluded instruments, p.
    assert.equal(fit!.firstStage.length, reference.firstStage.length, `${reference.name}: first stage rows`);
    reference.firstStage.forEach((stage, index) => {
      const actual = fit!.firstStage[index];
      assertCloseVector(
        actual.coefficients.map(value => value.beta),
        stage.coefficients.map(value => value.beta),
        TOLERANCE,
        `${reference.name} first stage ${stage.endog} beta`
      );
      assertCloseVector(
        actual.coefficients.map(value => value.se),
        stage.coefficients.map(value => value.se),
        TOLERANCE,
        `${reference.name} first stage ${stage.endog} se`
      );
      assertClose(actual.f, stage.f, TOLERANCE, `${reference.name} first stage F`);
      assert.equal(actual.df1, stage.df1, `${reference.name} first stage df1`);
      assert.equal(actual.df2, stage.df2, `${reference.name} first stage df2`);
      assertClose(actual.p, stage.p, TOLERANCE, `${reference.name} first stage p`);
    });

    // Sargan: n * R² of the 2SLS residuals on all instruments, df = #inst - #endog.
    assert.ok(fit!.sargan, `${reference.name}: Sargan expected for an over-identified model`);
    assert.equal(fit!.sargan!.df, reference.sargan.df, `${reference.name} Sargan df`);
    assertClose(fit!.sargan!.statistic, reference.sargan.statistic, TOLERANCE, `${reference.name} Sargan`);
    assertClose(fit!.sargan!.p, reference.sargan.p, TOLERANCE, `${reference.name} Sargan p`);

    // Wu–Hausman: classical F, identical in the homoskedastic and robust cases.
    assert.equal(fit!.wuHausman.df1, reference.wuHausman.df1, `${reference.name} Wu–Hausman df1`);
    assert.equal(fit!.wuHausman.df2, reference.wuHausman.df2, `${reference.name} Wu–Hausman df2`);
    assertClose(
      fit!.wuHausman.statistic,
      reference.wuHausman.statistic,
      TOLERANCE,
      `${reference.name} Wu–Hausman`
    );
    assertClose(fit!.wuHausman.p, reference.wuHausman.p, TOLERANCE, `${reference.name} Wu–Hausman p`);
  }
});

test('the IV harness rejects values outside the declared tolerance', () => {
  assert.throws(() => assertClose(1.001, 1, TOLERANCE));
  assert.throws(() => assertCloseVector([1, 2], [1, 3], TOLERANCE));
  assertClose(1.0000001, 1, TOLERANCE);
});
