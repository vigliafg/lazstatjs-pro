import test from 'node:test';
import assert from 'node:assert/strict';
import { fitPanel } from '../kernels/panel';
import { assertClose, assertCloseVector, loadFixture, type Tolerance } from './harness';

interface PanelFixtureCoefficient {
  term: string;
  beta: number;
  seCluster?: number;
  seClassic?: number;
  se?: number;
}

interface PanelFixtureCase {
  name: string;
  provenance: string;
  entity: string[];
  time: number[];
  y: number[];
  x: number[][];
  n: number;
  entities: number;
  periods: number;
  balanced: boolean;
  tbar: number;
  variance: { idiosyncratic: number; entity: number };
  theta: number;
  hausman: {
    statistic: number;
    rawStatistic: number;
    df: number;
    p: number;
    valid: boolean;
  };
  fe: {
    terms: string[];
    coefficients: PanelFixtureCoefficient[];
    fitted: number[];
    residuals: number[];
    entityEffects: number[];
    dfResidual: number;
    r2: { within: number; between: number; overall: number };
  };
  re: {
    terms: string[];
    coefficients: PanelFixtureCoefficient[];
    seSigmaE: number[];
    fitted: number[];
    residuals: number[];
    dispersion: number;
    sigma2Within: number;
    dfResidual: number;
    r2: { within: number; between: number; overall: number };
    plmR2: number;
  };
}

interface PanelFixture {
  source: string;
  generatedBy: string;
  formula: string;
  cases: PanelFixtureCase[];
}

const fixture = loadFixture<PanelFixture>('panel.json');

/**
 * Declared tolerance of the panel reference test (task requirement): 1e-6 on
 * coefficients, standard errors, variance components, theta and Hausman. The
 * kernel and plm share the algebra, so the observed differences are at the
 * 1e-13 level; the 1e-6 bound is kept as the contract, not as a fudge factor.
 */
const PANEL: Tolerance = { absolute: 1e-9, relative: 1e-6 };

/**
 * Compare a kernel fit with `plm` on both bundled cases.
 *
 * Definitions compared one-to-one:
 * - FE coefficients, cluster-robust (Arellano HC1) and classical standard
 *   errors, fitted values (alpha_i + x'b = fitted(plm) + fixef(plm)),
 *   residuals, entity effects and the three R².
 * - RE coefficients, classical standard errors, quasi-demeaned fitted values
 *   and residuals, dispersion, degrees of freedom and the three R².
 * - Swamy–Arora variance components, theta and the Hausman test
 *   (`plm::phtest`), including the `valid` flag that records whether
 *   `V_FE - V_RE` is positive definite.
 */
test('panel FE/RE matches the plm fixtures generated by the reference harness', () => {
  assert.ok(fixture.cases.length >= 2, 'expected the demo and a synthetic case');

  for (const reference of fixture.cases) {
    const fit = fitPanel({
      y: reference.y,
      x: reference.x,
      entity: reference.entity,
      time: reference.time,
      model: 'both',
    });
    assert.ok(fit, `${reference.name}: model did not converge`);

    assert.equal(fit.n, reference.n, `${reference.name} n`);
    assert.equal(fit.entities, reference.entities, `${reference.name} entities`);
    assert.equal(fit.periods, reference.periods, `${reference.name} periods`);
    assert.equal(fit.balanced, reference.balanced, `${reference.name} balanced`);

    // Swamy–Arora variance components and theta.
    assertClose(fit.variance.idiosyncratic, reference.variance.idiosyncratic, PANEL, `${reference.name} sigma2_e`);
    assertClose(fit.variance.entity, reference.variance.entity, PANEL, `${reference.name} sigma2_u`);
    assert.equal(fit.theta.length, reference.entities, `${reference.name} theta length`);
    for (const theta of fit.theta) {
      assertClose(theta, reference.theta, PANEL, `${reference.name} theta`);
    }

    // Fixed effects.
    assert.ok(fit.fe, `${reference.name}: missing FE fit`);
    const fe = fit.fe!;
    // The kernel knows only positions (`x1`, `x2`); the fixture keeps the R
    // names. Only the count is comparable.
    assert.equal(fe.terms.length, reference.fe.terms.length);
    assert.equal(fe.dfResidual, reference.fe.dfResidual);
    assertCloseVector(fe.coefficients.map(c => c.beta), reference.fe.coefficients.map(c => c.beta), PANEL, `${reference.name} FE beta`);
    assertCloseVector(fe.coefficients.map(c => c.se), reference.fe.coefficients.map(c => c.seCluster!), PANEL, `${reference.name} FE se cluster`);
    assertCloseVector(fe.coefficients.map(c => c.seClassic), reference.fe.coefficients.map(c => c.seClassic!), PANEL, `${reference.name} FE se classic`);
    assertCloseVector(fe.fitted, reference.fe.fitted, PANEL, `${reference.name} FE fitted`);
    assertCloseVector(fe.residuals, reference.fe.residuals, PANEL, `${reference.name} FE residuals`);
    assertClose(fe.r2Within, reference.fe.r2.within, PANEL, `${reference.name} FE R2 within`);
    assertClose(fe.r2Between, reference.fe.r2.between, PANEL, `${reference.name} FE R2 between`);
    assertClose(fe.r2Overall, reference.fe.r2.overall, PANEL, `${reference.name} FE R2 overall`);

    const entityOrder = [...new Set(reference.entity)];
    const effects = new Map((fe.entityEffects ?? []).map(entry => [entry.entity, entry.effect]));
    assertCloseVector(
      entityOrder.map(label => effects.get(label) ?? Number.NaN),
      reference.fe.entityEffects,
      PANEL,
      `${reference.name} entity effects`
    );

    // Random effects.
    assert.ok(fit.re, `${reference.name}: missing RE fit`);
    const re = fit.re!;
    assert.equal(re.terms.length, reference.re.terms.length);
    assert.equal(re.terms[0], '(Intercept)');
    assert.equal(re.dfResidual, reference.re.dfResidual);
    assertCloseVector(re.coefficients.map(c => c.beta), reference.re.coefficients.map(c => c.beta), PANEL, `${reference.name} RE beta`);
    assertCloseVector(re.coefficients.map(c => c.se), reference.re.coefficients.map(c => c.se!), PANEL, `${reference.name} RE se`);
    assertCloseVector(
      re.coefficients.map(c => c.seCluster),
      reference.re.coefficients.map(c => c.seCluster!),
      PANEL,
      `${reference.name} RE se cluster`
    );
    assertCloseVector(re.fitted, reference.re.fitted, PANEL, `${reference.name} RE fitted`);
    assertCloseVector(re.residuals, reference.re.residuals, PANEL, `${reference.name} RE residuals`);
    assertClose(re.dispersion, reference.re.dispersion, PANEL, `${reference.name} RE dispersion`);
    assertClose(re.sigma2, reference.re.sigma2Within, PANEL, `${reference.name} RE sigma2 within`);
    assertClose(re.r2Within, reference.re.r2.within, PANEL, `${reference.name} RE R2 within`);
    assertClose(re.r2Between, reference.re.r2.between, PANEL, `${reference.name} RE R2 between`);
    assertClose(re.r2Overall, reference.re.r2.overall, PANEL, `${reference.name} RE R2 overall`);

    // Documented definitional difference: plm's RE standard errors use the
    // residual variance of the quasi-demeaned regression (`re.dispersion`); the
    // alternative classical GLS scaling by sigma2_e reproduces `seSigmaE`.
    const scale = Math.sqrt(fit.variance.idiosyncratic / re.dispersion);
    assertCloseVector(
      re.coefficients.map(coefficient => coefficient.se * scale),
      reference.re.seSigmaE,
      PANEL,
      `${reference.name} RE se (sigma2_e scaling)`
    );

    // Hausman.
    assert.ok(fit.hausman, `${reference.name}: missing Hausman test`);
    assert.equal(fit.hausman!.df, reference.hausman.df);
    assert.equal(fit.hausman!.valid, reference.hausman.valid, `${reference.name} Hausman validity`);
    assertClose(fit.hausman!.statistic, reference.hausman.statistic, PANEL, `${reference.name} Hausman statistic`);
    assertClose(fit.hausman!.p, reference.hausman.p, PANEL, `${reference.name} Hausman p`);
    if (!reference.hausman.valid) {
      // The quadratic form is negative: the kernel takes the absolute value,
      // exactly like plm::phtest, and flags the test as invalid.
      assert.ok(reference.hausman.rawStatistic < 0, `${reference.name}: expected an indefinite difference`);
    }
  }
});

test('plm reports the quasi-demeaned R² for random effects (documented, not compared)', () => {
  // plm's summary.plm reports the R² of the transformed regression for RE, a
  // quantity that is not one of within/between/overall. Keeping the difference
  // here documents why the fixture computes the three definitions explicitly
  // and why only the FE within R² is read directly from plm.
  for (const reference of fixture.cases) {
    assert.ok(
      Math.abs(reference.re.plmR2 - reference.re.r2.within) > 1e-4,
      `${reference.name}: plm R² unexpectedly equals the within R²`
    );
  }
});

test('panel fixtures record the exact plm calls that produced them', () => {
  assert.match(fixture.source, /plm::plm/);
  assert.match(fixture.source, /random\.method|swar/);
  assert.match(fixture.source, /phtest/);
  assert.match(fixture.source, /vcovHC/);
  assert.equal(fixture.generatedBy, 'src/stats/reference/r/panel.R');
});
