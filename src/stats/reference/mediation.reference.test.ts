import test from 'node:test';
import assert from 'node:assert/strict';
import { fitMediation } from '../kernels/mediation';
import { assertClose, loadFixture, TOLERANCES } from './harness';

interface ReferenceEstimate {
  estimate: number;
  se: number;
}

interface MediationFixtureCase {
  name: string;
  outcome: number[];
  predictor: number[];
  mediator: number[];
  covariates: number[][];
  paths: {
    a: ReferenceEstimate;
    b: ReferenceEstimate;
    cPrime: ReferenceEstimate;
    cTotal: ReferenceEstimate;
  };
  effects: {
    indirect: ReferenceEstimate;
    direct: ReferenceEstimate;
    total: ReferenceEstimate;
    proportion: ReferenceEstimate;
  };
}

interface MediationFixture {
  source: string;
  generatedBy: string;
  cases: MediationFixtureCase[];
}

const fixture = loadFixture<MediationFixture>('mediation.json');

const TOLERANCE = TOLERANCES.rProbability; // 1e-6, as declared by the plan.

/**
 * The fixture is generated by `src/stats/reference/r/mediation.R` from
 * `lavaan::sem()` with delta-method standard errors (`se = "standard"`; recent
 * lavaan releases no longer accept the literal `se = "delta"`). The bootstrap
 * is intentionally not compared point by point: R and the kernel use
 * different PRNGs, so the fixture stores only estimates and delta-method SEs.
 */
test('mediation matches the lavaan::sem delta-method fixtures', () => {
  assert.ok(fixture.cases.length >= 3);
  for (const reference of fixture.cases) {
    const result = fitMediation({
      outcome: reference.outcome,
      predictor: reference.predictor,
      mediator: reference.mediator,
      covariates: reference.covariates,
      bootstrap: 0,
      seed: 20261103,
      level: 95,
    });
    assert.ok(result, `${reference.name}: model did not fit`);
    if (!result) continue;

    const pathPairs = [
      ['a', reference.paths.a, result.paths.a] as const,
      ['b', reference.paths.b, result.paths.b] as const,
      ['cPrime', reference.paths.cPrime, result.paths.cPrime] as const,
      ['cTotal', reference.paths.cTotal, result.paths.cTotal] as const,
    ];
    for (const [label, expected, actual] of pathPairs) {
      assertClose(actual.beta, expected.estimate, TOLERANCE, `${reference.name} ${label} beta`);
      assertClose(actual.se, expected.se, TOLERANCE, `${reference.name} ${label} se`);
    }

    const effectPairs = [
      ['indirect', reference.effects.indirect, result.effects.indirect] as const,
      ['direct', reference.effects.direct, result.effects.direct] as const,
      ['total', reference.effects.total, result.effects.total] as const,
      ['proportion', reference.effects.proportion, result.effects.proportion] as const,
    ];
    for (const [label, expected, actual] of effectPairs) {
      assertClose(actual.estimate, expected.estimate, TOLERANCE, `${reference.name} ${label} estimate`);
      assertClose(actual.se, expected.se, TOLERANCE, `${reference.name} ${label} se`);
    }

    // Sobel and the delta-method indirect SE coincide because a is
    // asymptotically independent of b in this recursive model.
    assertClose(
      result.sobel.se,
      reference.effects.indirect.se,
      TOLERANCE,
      `${reference.name} sobel se`
    );

    // The total effect fitted without the mediator is the same quantity as
    // c' + a b, which is what lavaan defines as `total`.
    assertClose(
      result.paths.cTotal.beta,
      result.paths.cPrime.beta + result.paths.a.beta * result.paths.b.beta,
      1e-10,
      `${reference.name} total decomposition`
    );

    // The fixture disables the bootstrap: no RNG is involved in this test.
    assert.equal(result.bootstrap, null);
  }
});
