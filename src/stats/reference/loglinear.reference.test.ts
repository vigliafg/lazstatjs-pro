import test from 'node:test';
import assert from 'node:assert/strict';
import { loglinearFit } from '../kernels/loglinear';
import { assertClose, assertCloseMatrix, loadFixture, TOLERANCES } from './harness';

interface LoglinearFixtureCase {
  name: string;
  rows: string[];
  cols: string[];
  observed: number[][];
  model: 'independence' | 'saturated';
  coefficients: { beta: number; se: number }[];
  deviance: number;
  df: number;
  p: number | null;
  nullDeviance: number;
  logLik: number;
  aic: number;
  expected: number[][];
  oddsRatio?: { oddsRatio: number; lo: number; hi: number };
}

interface LoglinearFixture {
  source: string;
  generatedBy: string;
  cases: LoglinearFixtureCase[];
}

const fixture = loadFixture<LoglinearFixture>('loglinear.json');

// The designed cases are small 2×2 and 3×3 tables. Coefficients, expected
// counts and G² use the shared 1e-8 algebraic tolerance: the kernel and R
// solve the same estimating equations, only the summation order differs.
// Standard errors are assembled through a different covariance path, so they
// keep the wider R probability tolerance (1e-6), exactly like the GLM fixture.
test('log-linear models match the R glm fixtures generated by the reference harness', () => {
  assert.ok(fixture.cases.length >= 4);
  assert.equal(fixture.source, 'R glm(family = poisson)');

  for (const reference of fixture.cases) {
    const fit = loglinearFit({
      observed: reference.observed,
      rowLabels: reference.rows,
      colLabels: reference.cols,
      model: reference.model,
      level: 95,
    });
    assert.ok(fit, `${reference.name}: model did not converge`);

    assert.equal(fit!.model, reference.model);
    assert.equal(fit!.rows, reference.rows.length);
    assert.equal(fit!.cols, reference.cols.length);
    assert.equal(
      fit!.n,
      reference.observed.flat().reduce((sum, value) => sum + value, 0),
      `${reference.name} n`
    );

    assert.equal(fit!.coefficients.length, reference.coefficients.length, `${reference.name} p`);
    reference.coefficients.forEach((expected, index) => {
      assertClose(
        fit!.coefficients[index].beta,
        expected.beta,
        TOLERANCES.r,
        `${reference.name} beta[${index}]`
      );
      assertClose(
        fit!.coefficients[index].se,
        expected.se,
        TOLERANCES.rProbability,
        `${reference.name} se[${index}]`
      );
    });

    assertCloseMatrix(
      fit!.expected,
      reference.expected,
      TOLERANCES.r,
      `${reference.name} expected`
    );
    assertClose(fit!.deviance, reference.deviance, TOLERANCES.r, `${reference.name} G²`);
    assert.equal(fit!.dfResidual, reference.df, `${reference.name} df`);
    assertClose(
      fit!.nullDeviance,
      reference.nullDeviance,
      TOLERANCES.r,
      `${reference.name} null deviance`
    );
    assertClose(fit!.logLik, reference.logLik, TOLERANCES.r, `${reference.name} logLik`);
    assertClose(fit!.aic, reference.aic, TOLERANCES.r, `${reference.name} AIC`);

    if (reference.p === null) {
      assert.ok(Number.isNaN(fit!.p), `${reference.name}: df = 0 has no p-value`);
    } else {
      assertClose(fit!.p, reference.p, TOLERANCES.rProbability, `${reference.name} p`);
    }

    if (reference.oddsRatio) {
      assert.ok(fit!.oddsRatio, `${reference.name}: interaction odds ratio`);
      assertClose(fit!.oddsRatio!.oddsRatio, reference.oddsRatio.oddsRatio, TOLERANCES.r);
      assertClose(fit!.oddsRatio!.lo, reference.oddsRatio.lo, TOLERANCES.r);
      assertClose(fit!.oddsRatio!.hi, reference.oddsRatio.hi, TOLERANCES.r);
    } else {
      assert.equal(fit!.oddsRatio, undefined, `${reference.name}: no 2×2 saturated interaction`);
    }
  }
});
