      )
    ),
    trend = list(
      name = "four-by-two",
      observed = unname(trend_observed),
      scores = trend_scores,
      statistic = unname(trend_fit$statistic),
      p = unname(trend_fit$p.value),
      proportions = unname(trend_observed[, 1] / rowSums(trend_observed))
    ),
    exact = list(
      twoByTwo = list(
        observed = unname(fisher_observed),
        p = unname(fisher_p)
      ),
      threeByTwo = list(
        observed = unname(exact_three_by_two),
        p = three_by_two_fit$p,
        statistic = three_by_two_fit$statistic,
        tables = three_by_two_fit$tables
      ),
      threeByThree = list(
        observed = unname(exact_three_by_three),
        p = three_by_three_fit$p,
        statistic = three_by_three_fit$statistic,
        tables = three_by_three_fit$tables
      )
    )
  ),
  output,
  auto_unbox = TRUE,
  pretty = TRUE,
  digits = NA
)
