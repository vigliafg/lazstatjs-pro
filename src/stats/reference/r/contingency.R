# Reference fixtures — contingency extensions (Mantel–Haenszel, trend, exact).
#
# Generates ../fixtures/contingency.json for the kernels implemented in
# src/stats/kernels/contingency.ts.
#
# Run from the repository root:
#   Rscript src/stats/reference/r/contingency.R
#
# The output is committed so `npm test` never needs R. Re-run it only when the
# datasets or the expected method change; review the diff before committing.
#
# Mantel–Haenszel: the zero-cell fixture follows the declared kernel rule
# (add 0.5 to every cell of a stratum when one cell is zero, then pool). The
# no-zero fixture is generated by stats::mantelhaen.test(correct = TRUE) and
# checks the same statistic without the correction.
#
# Trend: stats::prop.trend.test(x = first column, n = row totals, score).
#
# Exact R×C: base-R recursion over every table with the observed margins. The
# statistic is sum(|O - E|); the p-value sums the hypergeometric probabilities
# of the tables whose statistic is at least the observed one.

suppressMessages(library(jsonlite))

args <- commandArgs(trailingOnly = TRUE)
output <- if (length(args) >= 1) args[1] else "src/stats/reference/fixtures/contingency.json"

mh_manual <- function(strata, labels, correct = TRUE, conf.level = 0.95) {
  corrected <- lapply(strata, function(table) {
    matrix <- as.matrix(table)
    if (any(matrix == 0)) matrix + 0.5 else matrix
  })

  n <- vapply(corrected, sum, numeric(1))
  a <- vapply(corrected, function(table) table[1, 1], numeric(1))
  b <- vapply(corrected, function(table) table[1, 2], numeric(1))
  c <- vapply(corrected, function(table) table[2, 1], numeric(1))
  d <- vapply(corrected, function(table) table[2, 2], numeric(1))

  s_diag <- sum(a * d / n)
  s_off <- sum(b * c / n)
  odds_ratio <- s_diag / s_off

  delta <- sum(a - (a + b) * (a + c) / n)
  variance <- sum((a + b) * (c + d) * (a + c) * (b + d) / (n^2 * (n - 1)))
  yates <- if (correct && abs(delta) >= 0.5) 0.5 else 0
  chi2 <- (abs(delta) - yates)^2 / variance
  p <- pchisq(chi2, 1, lower.tail = FALSE)

  se <- sqrt(
    sum(((a + d) * a * d) / n^2) / (2 * s_diag^2) +
      sum((((a + d) * b * c + (b + c) * a * d)) / n^2) / (2 * s_diag * s_off) +
      sum(((b + c) * b * c) / n^2) / (2 * s_off^2)
  )
  z <- qnorm(1 - (1 - conf.level) / 2)

  stratum_results <- lapply(seq_along(strata), function(index) {
    list(
      label = labels[[index]],
      oddsRatio = a[[index]] * d[[index]] / (b[[index]] * c[[index]]),
      logOddsRatio = log(a[[index]] * d[[index]] / (b[[index]] * c[[index]])),
      weight = b[[index]] * c[[index]] / n[[index]],
      corrected = any(as.matrix(strata[[index]]) == 0)
    )
  })

  list(
    oddsRatio = odds_ratio,
    logOddsRatio = log(odds_ratio),
    standardError = se,
    lo = log(odds_ratio) - z * se,
    hi = log(odds_ratio) + z * se,
    chi2 = chi2,
    p = p,
    strata = stratum_results
  )
}

exact_rc <- function(observed, budget = 200000) {
  observed <- as.matrix(observed)
  rows <- nrow(observed)
  cols <- ncol(observed)
  row_totals <- rowSums(observed)
  col_totals <- colSums(observed)
  n <- sum(observed)
  expected <- outer(row_totals, col_totals) / n
  observed_statistic <- sum(abs(observed - expected))

  log_fact <- c(0, cumsum(log(seq_len(n))))
  log_factorial <- function(value) log_fact[value + 1]

  log_probability <- function(table) {
    value <- sum(log_factorial(row_totals)) + sum(log_factorial(col_totals)) -
      log_factorial(n) - sum(log_factorial(table))
    value
  }

  table <- matrix(0, rows, cols)
  remaining <- as.numeric(col_totals)
  count <- 0
  total <- 0
  tail <- 0
  aborted <- FALSE

  visit <- function(row_index) {
    if (aborted) return(invisible(NULL))
    if (row_index == rows) {
      table[row_index, ] <<- remaining
      count <<- count + 1
      if (count > budget) {
        aborted <<- TRUE
        return(invisible(NULL))
      }
      probability <- exp(log_probability(table))
      total <<- total + probability
      if (sum(abs(table - expected)) >= observed_statistic - 1e-12) {
        tail <<- tail + probability
      }
      return(invisible(NULL))
    }

    distribute <- function(col_index, left) {
      if (aborted) return(invisible(NULL))
      if (col_index == cols + 1) {
        if (left == 0) visit(row_index + 1)
        return(invisible(NULL))
      }
      maximum <- min(left, remaining[[col_index]])
      for (value in 0:maximum) {
        table[row_index, col_index] <<- value
        remaining[[col_index]] <<- remaining[[col_index]] - value
        distribute(col_index + 1, left - value)
        remaining[[col_index]] <<- remaining[[col_index]] + value
        if (aborted) return(invisible(NULL))
      }
      table[row_index, col_index] <<- 0
      invisible(NULL)
    }

    distribute(1, row_totals[[row_index]])
    invisible(NULL)
  }

  visit(1)
  if (aborted) {
    return(list(tooMany = TRUE, tables = count))
  }
  list(
    p = min(1, max(0, tail / total)),
    statistic = observed_statistic,
    tables = count
  )
}

# --- Mantel–Haenszel --------------------------------------------------------

mh_zero_strata <- list(
  matrix(c(12, 20, 18, 9), nrow = 2, byrow = TRUE),
  matrix(c(7, 15, 19, 11), nrow = 2, byrow = TRUE),
  matrix(c(0, 8, 6, 10), nrow = 2, byrow = TRUE)
)
mh_zero_labels <- c("Stratum A", "Stratum B", "Stratum C")

mh_no_zero_strata <- list(
  matrix(c(12, 20, 18, 9), nrow = 2, byrow = TRUE),
  matrix(c(7, 15, 19, 11), nrow = 2, byrow = TRUE),
  matrix(c(5, 9, 11, 4), nrow = 2, byrow = TRUE)
)
mh_no_zero_labels <- c("Stratum A", "Stratum B", "Stratum D")

mh_no_zero_array <- array(
  unlist(mh_no_zero_strata),
  dim = c(2, 2, length(mh_no_zero_strata))
)
mh_no_zero_fit <- mantelhaen.test(mh_no_zero_array, correct = TRUE)

# --- Cochran–Armitage trend -------------------------------------------------

trend_observed <- matrix(c(18, 12, 25, 15, 32, 8, 40, 5), nrow = 4, byrow = TRUE)
trend_scores <- c(1, 2, 3, 4)
trend_fit <- prop.trend.test(
  x = trend_observed[, 1],
  n = rowSums(trend_observed),
  score = trend_scores
)

# --- Exact tests ------------------------------------------------------------

fisher_observed <- matrix(c(30, 20, 15, 35), nrow = 2, byrow = TRUE)
fisher_p <- fisher.test(fisher_observed, alternative = "two.sided")$p.value

exact_three_by_two <- matrix(c(12, 7, 8, 10, 5, 13), nrow = 3, byrow = TRUE)
exact_three_by_three <- matrix(c(10, 5, 3, 6, 12, 4, 2, 3, 9), nrow = 3, byrow = TRUE)

three_by_two_fit <- exact_rc(exact_three_by_two)
three_by_three_fit <- exact_rc(exact_three_by_three)
stopifnot(!isTRUE(three_by_two_fit$tooMany), !isTRUE(three_by_three_fit$tooMany))

write_json(
  list(
    source = "R stats::mantelhaen.test(), stats::prop.trend.test(), stats::fisher.test() and base-R exact enumeration",
    generatedBy = "src/stats/reference/r/contingency.R",
    mantelHaenszel = list(
      name = "three-strata-zero-cell",
      strata = lapply(mh_zero_strata, function(table) unname(as.matrix(table))),
      labels = mh_zero_labels,
      expected = mh_manual(mh_zero_strata, mh_zero_labels, correct = TRUE)
    ),
    mantelHaenszelNoZero = list(
      name = "three-strata-no-zero-cell",
      strata = lapply(mh_no_zero_strata, function(table) unname(as.matrix(table))),
      labels = mh_no_zero_labels,
      expected = list(
        oddsRatio = unname(mh_no_zero_fit$estimate),
        chi2 = unname(mh_no_zero_fit$statistic),
