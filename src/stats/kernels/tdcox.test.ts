const close = (actual: number, expected: number, tolerance = 1e-5) =>
  assert.ok(Math.abs(actual - expected) < tolerance, `${actual} != ${expected}`);

test('time-dependent Cox matches survival::coxph start-stop', () => {
  const start = rows.map(row => Number(row[0]));
  const stop = rows.map(row => Number(row[1]));
  const event = rows.map(row => Number(row[2]));
  const x = rows.map(row => Number(row[3]));
  const stats = timeDependentCoxStats({
    start,
    stop,
    event,
    covariates: [{ name: 'x', values: x }],
    level: 95,
  });
  assert.ok(stats);
  if (!stats) return;
  close(stats.coefficients[0].beta, -2.105292, 1e-4);
  close(stats.coefficients[0].se, 0.91523316, 1e-5);
  close(stats.logLik, -10.17469, 1e-4);
});
