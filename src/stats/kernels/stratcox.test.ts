const close = (actual: number, expected: number, tolerance = 1e-6) =>
  assert.ok(Math.abs(actual - expected) < tolerance, `${actual} != ${expected}`);

test('stratified Cox matches survival::coxph with strata', () => {
  const time = rows.map(row => Number(row[0]));
  const event = rows.map(row => Number(row[1]));
  const x = rows.map(row => Number(row[2]));
  const strata = rows.map(row => row[3]);
  const stats = stratifiedCoxStats({ time, event, covariates: [{ name: 'x', values: x }], strata, level: 95 });
  assert.ok(stats);
  if (!stats) return;
  assert.equal(stats.strata, 2);
  close(stats.coefficients[0].beta, 0.278952, 1e-5);
  close(stats.coefficients[0].se, 0.26836459, 1e-6);
  close(stats.logLik, -36.97681, 1e-4);
});
