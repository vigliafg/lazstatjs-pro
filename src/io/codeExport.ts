import type { GridData } from '../grid/types';
import type { ProjectParams } from './project';

export type CodeLanguage = 'r' | 'python';

const rName = (name: string): string =>
  /^[A-Za-z_.][A-Za-z0-9_.]*$/.test(name) && !/^(if|else|for|while|function|TRUE|FALSE|NULL)$/i.test(name)
    ? name
    : `\`${name.replace(/`/g, '\\`')}\``;

const pyName = (name: string): string => `df[${JSON.stringify(name)}]`;

const rVector = (names: string[]): string => `c(${names.map(rName).join(', ')})`;
const pyVector = (names: string[]): string => `[${names.map(name => JSON.stringify(name)).join(', ')}]`;

const header = (language: CodeLanguage): string =>
  language === 'r'
    ? '# Generated by LazStats\nlibrary(readr)\ndf <- read_csv("data.csv")\n'
    : '# Generated by LazStats\nimport pandas as pd\ndf = pd.read_csv("data.csv")\n';

/** Reproducible snippet for the analyses where a short, honest translation exists. */
export const buildAnalysisCode = (
  analysisId: string,
  grid: GridData,
  params: ProjectParams,
  ciLevel: number,
  language: CodeLanguage
): string | null => {
  const col = (index: number): string => grid.cols[index]?.name ?? `V${index + 1}`;
  const level = (ciLevel / 100).toFixed(2);
  const lines = [header(language)];

  if (analysisId === 'descriptive') {
    const names = params.descVars.map(col);
    lines.push(
      language === 'r'
        ? `summary(df[, ${rVector(names)}])`
        : `print(df[${pyVector(names)}].describe())`
    );
    return lines.join('\n');
  }

  if (analysisId === 'ttest') {
    const { type, var1, var2, mu, equalVar } = params.ttest;
    if (language === 'r') {
      if (type === 'one') lines.push(`t.test(df$${rName(col(var1))}, mu = ${mu}, conf.level = ${level})`);
      else if (type === 'dep') lines.push(`t.test(df$${rName(col(var1))}, df$${rName(col(var2))}, paired = TRUE, conf.level = ${level})`);
      else lines.push(`t.test(df$${rName(col(var1))}, df$${rName(col(var2))}, var.equal = ${equalVar ? 'TRUE' : 'FALSE'}, conf.level = ${level})`);
    } else {
      lines.push('from scipy import stats');
      if (type === 'one') lines.push(`print(stats.ttest_1samp(${pyName(col(var1))}, ${mu}))`);
      else if (type === 'dep') lines.push(`print(stats.ttest_rel(${pyName(col(var1))}, ${pyName(col(var2))}))`);
      else lines.push(`print(stats.ttest_ind(${pyName(col(var1))}, ${pyName(col(var2))}, equal_var=${equalVar ? 'True' : 'False'}))`);
    }
    return lines.join('\n');
  }

  if (analysisId === 'anova') {
    const { dep, grp } = params.anova;
    lines.push(
      language === 'r'
        ? `model <- aov(df$${rName(col(dep))} ~ factor(df$${rName(col(grp))}), data = df)\nsummary(model)`
        : `import statsmodels.formula.api as smf\nfrom statsmodels.stats.anova import anova_lm\nmodel = smf.ols('Q("${col(dep)}") ~ C(Q("${col(grp)}"))', data=df).fit()\nprint(anova_lm(model))`
    );
    return lines.join('\n');
  }

  if (analysisId === 'regression') {
    const { dep, indeps } = params.reg;
    const names = indeps.map(col);
    lines.push(
      language === 'r'
        ? `model <- lm(df$${rName(col(dep))} ~ ${names.map(name => `df$${rName(name)}`).join(' + ')}, data = df)\nsummary(model)`
        : `import statsmodels.formula.api as smf\nmodel = smf.ols('Q("${col(dep)}") ~ ${names.map(name => `Q("${name}")`).join(' + ')}', data=df).fit()\nprint(model.summary())`
    );
    return lines.join('\n');
  }

  if (analysisId === 'correlation') {
    const names = params.corr.vars.map(col);
    if (language === 'r') {
      lines.push(`cor(df[, ${rVector(names)}], use = "complete.obs")`);
    } else {
      lines.push(`print(df[${pyVector(names)}].corr())`);
    }
    return lines.join('\n');
  }

  if (analysisId === 'logistic') {
    const { outcome, predictors } = params.logistic;
    const names = predictors.map(col);
    lines.push(
      language === 'r'
        ? `model <- glm(df$${rName(col(outcome))} ~ ${names.map(name => `df$${rName(name)}`).join(' + ')}, family = binomial(), data = df)\nsummary(model)`
        : `import statsmodels.formula.api as smf\nmodel = smf.logit('Q("${col(outcome)}") ~ ${names.map(name => `Q("${name}")`).join(' + ')}', data=df).fit()\nprint(model.summary())`
    );
    return lines.join('\n');
  }

  return null;
};
